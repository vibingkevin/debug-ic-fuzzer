"""Build each selected commit with baseline and sut."""

from contextlib import ExitStack
from datetime import datetime
from pathlib import Path
import argparse
import json
import subprocess
import tarfile

import yaml
from tqdm import tqdm

from impl import config
from impl.build import build_project
from impl.collection import collect_cache_files
from impl.comparison import collect_product_hashes, compare_products, save_product_contents
from impl.config import Compilers, Project, load_config, resolve_native_home
from impl.repository import prepare_repository, create_detached_worktree, activate_worktree
from impl.summary import write_run_summary


def replay_commits(compilers_config_path: Path, project_config_path: Path, *, start_at: int = 0, commit_count: int | None = None) -> int:
    """Replay both compilers, collect results, and stop after a failed commit pair.

    Args:
        compilers_config_path: Compiler configuration path, absolute or relative to PROJECT_ROOT.
        project_config_path: Project configuration path, absolute or relative to PROJECT_ROOT.
        start_at: Zero-based offset in the ordered YAML commit range.
        commit_count: Maximum commits to replay, or None for the remaining range.

    Returns:
        0 if each pair matches, both builds fail, or both links are UP-TO-DATE, unless every pair
        has both builds fail; otherwise 1. Writes results and worktrees under PROJECT_ROOT;
        configuration/setup errors propagate.
    """
    if start_at < 0:
        raise ValueError("--start-at must be nonnegative")
    if commit_count is not None and commit_count <= 0:
        raise ValueError("--commit-count must be positive")
    compilers_config_path = (config.PROJECT_ROOT / compilers_config_path).resolve()
    project_config_path = (config.PROJECT_ROOT / project_config_path).resolve()
    compilers = load_config(compilers_config_path, Compilers).compilers
    build_options = {"force_link": True} if any(compiler.clean_build for compiler in compilers.values()) else {}
    project_config = load_config(project_config_path, Project)
    project_config.gradle_args = [arg.replace("{config_dir}", str(project_config_path.parent)) for arg in project_config.gradle_args]
    tool_directory = config.PROJECT_ROOT
    bare_repository, commit_ids = prepare_repository(tool_directory / "repos", project_config)
    total_commits = len(commit_ids)
    if start_at >= total_commits:
        raise ValueError(f"--start-at {start_at} is outside the {total_commits}-commit range")
    commit_ids = commit_ids[start_at : None if commit_count is None else start_at + commit_count]
    print(f"Repository ready. Preparing to replay {len(commit_ids)} commits (start-at={start_at}, total={total_commits}).", flush=True)
    run_directory = tool_directory / "run" / f"{compilers_config_path.stem}-{project_config_path.stem}-{datetime.now():%Y%m%d-%H%M%S-%f}"
    run_directory.mkdir(parents=True)
    (run_directory / "range.json").write_text(json.dumps(dict(total_commits=total_commits, start_at=start_at, commit_count=len(commit_ids), commits=commit_ids), indent=2) + "\n")
    with ExitStack() as compiler_cleanup:
        native_homes = {variant: resolve_native_home(compiler_config, compilers_config_path.parent, compiler_cleanup, run_directory) for variant, compiler_config in compilers.items()}
        for variant in ("baseline", "sut"):
            create_detached_worktree(bare_repository, run_directory / variant, commit_ids[0])
        failed = False
        successful_commits = both_failed_commits = 0
        progress = compiler_cleanup.enter_context(tqdm(total=len(commit_ids), desc="Commits", unit="commit", mininterval=0))
        for commit_index, commit_id in enumerate(commit_ids):
            # for each commit
            variant_results = {}
            for variant in ("baseline", "sut"):
                # for each kotlin compiler variant
                record_stem = f"{commit_index:04d}-{commit_id[:12]}-{variant}"
                with activate_worktree(bare_repository, run_directory / variant, commit_id) as project_directory:
                    # run the build
                    build_result = build_project(project_directory, project_config, compilers[variant], native_homes[variant], record_stem, **build_options)
                    build_result.update(commit=commit_id, variant=variant, cache_files=None, artifacts=None, rebuilt_cache_count=None)
                    try:
                        # collect cache files generated by this build
                        if build_result["task_state"] != "UP-TO-DATE":
                            build_result["cache_files"] = collect_cache_files(build_result, run_directory / "store")
                            # collect product hashes if build was successful
                            if build_result["exit_code"] == 0 and build_result["error"] is None:
                                collect_product_hashes(build_result)
                    except (ValueError, OSError, subprocess.CalledProcessError) as error:
                        build_result["error"] = build_result["error"] or str(error)
                    variant_results[variant] = build_result
                    (run_directory / f"{record_stem}.json").write_text(json.dumps(build_result, ensure_ascii=False, indent=2) + "\n")
                tqdm.write(f"{commit_index:04d} {commit_id[:12]} {variant}: exit={build_result['exit_code']} error={build_result['error']}")
            comparison = {"error": "Build or collection failed"}
            try:
                if all(result["exit_code"] != 0 for result in variant_results.values()):
                    comparison = dict(strict_equal=None, production_equal=None, both_failed=True)
                elif any(result["exit_code"] != 0 or result["error"] is not None for result in variant_results.values()):
                    save_product_contents(variant_results)
                else:
                    # compare build products
                    comparison = compare_products(variant_results)
            except (ValueError, OSError) as error:
                comparison = {"error": str(error)}
            (run_directory / f"{commit_index:04d}-{commit_id[:12]}-comparison.json").write_text(json.dumps(comparison, indent=2) + "\n")
            tqdm.write(f"{commit_index:04d} comparison: {comparison}")
            successful_commits += int(all(result["exit_code"] == 0 and result["error"] is None for result in variant_results.values()))
            both_failed_commits += int(comparison.get("both_failed", False))
            failed = "error" in comparison or comparison.get("production_equal") is False
            progress.update(1)
            if failed:
                break
        progress.close()
        write_run_summary(run_directory, bare_repository)
        print(run_directory, flush=True)
        print(f"Successful builds (baseline + sut): {successful_commits}/{len(commit_ids)} commits; both failed: {both_failed_commits}.", flush=True)
        return int(failed or both_failed_commits == len(commit_ids))


def main():
    """Read CLI arguments and return the replay status; exit with 2 on setup errors."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--compilers", required=True, type=Path)
    parser.add_argument("--project", required=True, type=Path)
    parser.add_argument("--start-at", type=int, default=0, help="Zero-based offset in the ordered YAML commit range (default: 0)")
    parser.add_argument("--commit-count", type=int, help="Maximum commits to replay (default: all remaining commits)")
    args = parser.parse_args()
    try:
        return replay_commits(args.compilers, args.project, start_at=args.start_at, commit_count=args.commit_count)
    except (ValueError, OSError, subprocess.CalledProcessError, tarfile.TarError, yaml.YAMLError) as error:
        parser.exit(2, f"{error}\n")


if __name__ == "__main__":
    raise SystemExit(main())
